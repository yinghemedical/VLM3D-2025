#!/usr/bin/env python3
"""Create a portable runtime view of the 8B MedM-VL checkpoint.

The original checkpoint's config.json contains absolute paths from Jiawei's
old workspace.  This script symlinks the weight/tokenizer files and writes a
patched config.json that points at the local SigLIP2 and Qwen3-8B assets.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--src", required=True, help="Original 8B checkpoint directory")
    p.add_argument("--dst", required=True, help="Runtime checkpoint directory")
    p.add_argument("--cache-dir", required=True, help="Local Hugging Face cache_dir_hf")
    p.add_argument("--siglip-dir", required=True, help="Local SigLIP2 snapshot directory")
    p.add_argument("--qwen-dir", required=True, help="Local Qwen3-8B directory")
    p.add_argument(
        "--attn-implementation",
        default="sdpa",
        help="LLM attention backend used at inference (sdpa works without flash-attn)",
    )
    return p.parse_args()


def main() -> None:
    args = parse_args()
    src = Path(args.src).resolve()
    dst = Path(args.dst)
    cache_dir = str(Path(args.cache_dir).resolve())
    siglip_dir = str(Path(args.siglip_dir).resolve())
    qwen_dir = str(Path(args.qwen_dir).resolve())

    if not (src / "config.json").is_file():
        raise FileNotFoundError(f"missing {src / 'config.json'}")
    if not (src / "model.safetensors.index.json").is_file():
        raise FileNotFoundError(f"missing {src / 'model.safetensors.index.json'}")

    if dst.exists():
        # Only ever recreate this generated runtime directory.
        marker = dst / ".runtime_model"
        if marker.exists() or not any(dst.iterdir()):
            shutil.rmtree(dst)
        else:
            raise RuntimeError(f"refusing to remove non-empty non-runtime dir: {dst}")
    dst.mkdir(parents=True, exist_ok=True)
    (dst / ".runtime_model").write_text("generated by prepare_runtime_model.py\n")

    for path in sorted(src.iterdir()):
        if path.name == "config.json" or path.is_dir():
            continue
        target = dst / path.name
        os.symlink(path.resolve(), target)

    cfg = json.loads((src / "config.json").read_text())
    cfg["cache_dir_hf"] = cache_dir
    cfg["encoder_image_name_or_path"] = siglip_dir
    cfg["llm_name_or_path"] = qwen_dir
    cfg["llm_attn_implementation"] = args.attn_implementation
    for key in ("encoder_image_config", "llm_config"):
        if isinstance(cfg.get(key), dict):
            cfg[key]["_name_or_path"] = siglip_dir if key == "encoder_image_config" else qwen_dir
    (dst / "config.json").write_text(json.dumps(cfg, indent=2) + "\n")

    manifest = {
        "source": str(src),
        "runtime": str(dst),
        "cache_dir_hf": cache_dir,
        "encoder_image_name_or_path": siglip_dir,
        "llm_name_or_path": qwen_dir,
        "llm_attn_implementation": args.attn_implementation,
        "linked_files": sorted(p.name for p in dst.iterdir() if p.is_symlink()),
    }
    (dst / "runtime_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
